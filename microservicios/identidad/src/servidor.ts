import { instalarHttp } from './http.js';
import swagger from 'swagger-ui-express';
import { readFileSync } from 'node:fs';
import express from 'express';
import { Pool } from 'pg';
import { randomUUID } from 'node:crypto';
import { migrarSeguridad, rutasSeguridad } from './seguridad.js';
const app=express();app.disable('x-powered-by');instalarHttp(app,'identidad');
app.use((req,res,next)=>{if(req.url.startsWith('/api/v1/'))req.url=req.url.slice('/api/v1'.length);next();});
app.use(express.json({limit:'32kb'}));
const pool=new Pool({host:process.env.DB_HOST,port:Number(process.env.DB_PORT??5432),database:process.env.DB_NAME,user:process.env.DB_USER,password:process.env.DB_PASSWORD});
app.use('/docs',swagger.serveFiles(JSON.parse(readFileSync('/app/contrato.json','utf8'))),swagger.setup(JSON.parse(readFileSync('/app/contrato.json','utf8'))));
app.get('/openapi.json',(_req,res)=>{res.type('application/json').send(readFileSync('/app/contrato.json'));});
app.get('/salud',async(_req,res)=>{try{await pool.query('SELECT 1');res.json({servicio:'identidad',estado:'saludable'});}catch{res.status(503).json({servicio:'identidad'});}});
rutasSeguridad(app,pool);
app.use((_req,res)=>{res.status(404).json({detalle:'Ruta no disponible'});});
app.use((_error:unknown,_req:express.Request,res:express.Response,_next:express.NextFunction)=>{res.status((_error as any)?.status===400?400:500).json({detalle:'No se pudo completar la operación'});});
await migrarSeguridad(pool);
app.listen(Number(process.env.PORT??3000),'0.0.0.0');
